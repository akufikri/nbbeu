            <div class="clause__item">
                <h2>1. Nama &amp; Alamat Pejabat Berdaftar</h2>
                <p>Kesatuan ini dikenali sebagai <strong>North Borneo Banking Executive Union (NBBEU)</strong>. Pejabat berdaftar kesatuan ialah Lot 1, Blok A, Jalan Ikan Juara 1, Tingkat 2, Sadong Jaya, 88818 Kota Kinabalu, Sabah.</p>
            </div>

            <div class="clause__item">
                <h2>2. Tujuan Kesatuan</h2>
                <p>Tujuan Kesatuan ini ialah untuk:</p>
                <ul>
                    <li>Mengorganisasikan pekerja-pekerja bank dan memajukan kepentingan mereka dalam bidang perhubungan perusahaan, kemasyarakatan dan ilmu pengetahuan.</li>
                    <li>Mengatur perhubungan di antara pekerja dengan majikan bagi melaksanakan perhubungan perusahaan yang baik dan harmoni, meningkatkan daya pengeluaran serta mengekalkan keselamatan pekerjaan, sukatan gaji yang adil dan syarat-syarat pekerjaan yang berpatutan.</li>
                    <li>Memajukan kebajikan anggota dari segi sosial, ekonomi dan pendidikan dengan cara yang sah di sisi undang-undang.</li>
                    <li>Memberi bantuan guaman kepada anggota berhubung dengan pekerjaan mereka jika dipersetujui oleh Majlis Jawatankuasa Agung.</li>
                    <li>Menganjurkan kursus, dialog, seminar dan sebagainya untuk faedah anggota-anggota Kesatuan.</li>
                </ul>
            </div>

            <div class="clause__item">
                <h2>3. Kelayakan Keahlian</h2>
                <p>Keanggotaan Kesatuan ini terbuka kepada <strong>pekerja bank</strong> yang digaji oleh perbankan kecuali mereka yang memegang jawatan pengurusan, eksekutif, sulit atau keselamatan. Pekerja-pekerja itu hendaklah:</p>
                <ul>
                    <li>Berumur lebih dari 16 tahun dan mempunyai tempat kerjanya di Sabah.</li>
                    <li>Seseorang yang sedang mendapat pendidikan dalam sesebuah sekolah, politeknik, kolej, universiti atau institusi lain tidak boleh menjadi anggota Kesatuan kecuali jika ia sebenarnya seorang pekerja menurut takrif Akta Kesatuan Sekerja 1959 dan berumur lebih dari 18 tahun.</li>
                </ul>
                <p>Permohonan untuk menjadi anggota hendaklah dilakukan dengan mengisi borang yang ditentukan oleh Kesatuan dan menyampaikannya kepada Setiausaha Cawangan untuk kelulusan Majlis Jawatankuasa Agung.</p>
            </div>

            <div class="clause__item">
                <h2>4. Yuran &amp; Tunggakan</h2>
                <p>Yuran Kesatuan adalah seperti berikut:</p>
                <ul>
                    <li><strong>Yuran Masuk:</strong> RM 15.00</li>
                    <li><strong>Yuran Bulanan:</strong> RM 35.00</li>
                </ul>
                <p>Yuran bulanan hendaklah dijelaskan sebelum tujuh (7) haribulan pada tiap-tiap bulan. Seseorang anggota yang terhutang yuran selama tiga bulan berturut-turut akan hilang haknya sebagai anggota kesatuan dan sekiranya masih terhutang selama enam bulan berturut-turut dengan sendirinya terhenti dari menjadi anggota Kesatuan.</p>
                <p>Seseorang yang terhenti daripada menjadi anggota kerana tunggakan yuran boleh memohon semula untuk menjadi anggota mengikut prosedur permohonan biasa.</p>
            </div>

            <div class="clause__item">
                <h2>5. Berhenti Menjadi Anggota</h2>
                <p>Seseorang anggota yang ingin berhenti menjadi anggota Kesatuan hendaklah memberi notis secara bertulis sekurang-kurangnya seminggu sebelum tarikh berhenti kepada Setiausaha Cawangan dan hendaklah menjelaskan terlebih dahulu semua tunggakan yuran dan hutang (jika ada).</p>
                <p>Seseorang yang diterima masuk menjadi anggota dan kemudian berhenti daripada tempat kerjanya, tred atau industri seperti dinyatakan dalam Peraturan 3(1) akan dengan sendirinya terhenti dari menjadi anggota Kesatuan.</p>
            </div>

            <div class="clause__item">
                <h2>6. Hak Anggota</h2>
                <p>Semua anggota mempunyai hak yang sama dalam Kesatuan kecuali dalam perkara-perkara tertentu yang dinyatakan dalam peraturan-peraturan ini.</p>
            </div>

            <div class="clause__item">
                <h2>7. Kewajipan &amp; Tanggungjawab Anggota</h2>
                <p>Setiap anggota bertanggungjawab untuk:</p>
                <ul>
                    <li>Menjelaskan yurannya menepati masa dan mendapatkan resit rasmi bagi bayarannya. Pembayaran yuran bulanan dalam tempoh masa yang ditetapkan adalah tanggungjawab setiap anggota dan bukannya tanggungjawab pegawai-pegawai Kesatuan.</li>
                    <li>Memberitahu Setiausaha Cawangan dengan segera apabila berpindah tempat tinggal atau bertukar tempat kerja.</li>
                    <li>Berkelakuan baik semasa menghadiri mesyuarat Kesatuan atau menggunakan pejabat Kesatuan.</li>
                    <li>Tidak mengeluarkan sebarang dokumen atau surat pekeliling tentang Kesatuan tanpa mendapat kelulusan Majlis Jawatankuasa Agung.</li>
                    <li>Tidak mendedahkan sebarang hal tentang kegiatan Kesatuan kepada orang yang bukan anggota atau kepada pertubuhan lain atau pihak akhbar tanpa mendapat izin Majlis Jawatankuasa Agung.</li>
                </ul>
            </div>

            <div class="clause__item">
                <h2>8. Tindakan Tatatertib</h2>
                <p>Majlis Jawatankuasa Agung boleh menggantung atau memecat keanggotaan atau melarang daripada memegang jawatan seseorang anggota jika didapati bersalah kerana cuba hendak merosakkan Kesatuan atau melakukan perbuatan yang melanggar peraturan-peraturan ini atau melibatkan diri dengan sebarang perbuatan mencela, mengeji atau mencerca Kesatuan, pegawai atau dasar Kesatuan.</p>
                <p>Sebelum tindakan tersebut diambil, kesatuan hendaklah:</p>
                <ul>
                    <li>Memberi peluang kepada anggota berkenaan untuk membela diri terhadap tuduhan berkenaan.</li>
                    <li>Menyatakan secara bertulis dan jelas bentuk dan alasan tentang penggantungan, pemecatan atau larangan tersebut.</li>
                    <li>Menyatakan tempoh ianya berkuatkuasa dan syarat-syarat yang membolehkan ia ditarik balik.</li>
                </ul>
                <p>Jika seseorang yang telah digantung faedahnya, dipecat atau dilarang daripada memegang jawatan berasa terkilan, dia berhak merujukkan kilanan berkenaan melalui Majlis Jawatankuasa Agung untuk diselesaikan oleh Jemaah Penimbangtara atau merayu terus kepada Persidangan Perwakilan.</p>
            </div>

            <div class="clause__item">
                <h2>9. Mogok &amp; Pertikaian Perusahaan</h2>
                <p>Jika seseorang anggota tidak berpuas hati dengan syarat-syarat pekerjaannya atau sebarang hal yang lain, ia bolehlah mengemukakan aduannya kepada Setiausaha Cawangan secara bertulis untuk diambil tindakan sewajarnya.</p>
                <p>Kesatuan tidak boleh menganjurkan mogok dan anggota-anggotanya tidak dibenarkan menjalankan mogok tanpa mendapat kelulusan Majlis Jawatankuasa Agung terlebih dahulu dan tanpa mendapat persetujuan dengan undi rahsia sekurang-kurangnya 2/3 daripada jumlah anggota yang layak mengundi.</p>
                <p>Mana-mana anggota Kesatuan yang memulakan mogok yang melanggar Akta Kesatuan Sekerja 1959 atau peraturan-peraturan ini akan terhenti dengan sendirinya daripada menjadi anggota Kesatuan.</p>
            </div>

            <div class="clause__item">
                <h2>10. Penyelesaian Pertikaian Dalam Kesatuan</h2>
                <p>Tiap-tiap pertikaian yang berlaku di antara seseorang anggota dengan Kesatuan atau pegawai kesatuan hendaklah diselesaikan melalui penimbangtaraan oleh Jemaah Penimbangtara yang terdiri dari lima (5) orang yang dilantik dalam Persidangan Perwakilan Kesatuan.</p>
                <p>Jika tiada keputusan dibuat mengenai suatu pertikaian dalam tempoh empat puluh (40) hari selepas permohonan dibuat kepada kesatuan, anggota atau seseorang yang terkilan itu boleh memohon kepada Mahkamah Sesyen.</p>
            </div>

            <div class="clause__item">
                <h2>11. Pindaan Peraturan</h2>
                <p>Pindaan kepada peraturan-peraturan yang akan meningkatkan lagi tanggungan anggota untuk mencarum, atau mengurangkan faedah yang dinikmatinya hanya boleh dibuat jika diluluskan oleh anggota-anggota dengan undi rahsia.</p>
                <p>Pindaan peraturan-peraturan lain boleh dibuat dengan kelulusan Persidangan Perwakilan yang diadakan menurut peraturan-peraturan ini atau dengan undi rahsia. Tiap-tiap pindaan peraturan-peraturan hendaklah berkuatkuasa dari tarikh pindaan itu didaftarkan oleh Ketua Pengarah Kesatuan Sekerja.</p>
            </div>

            <div class="clause__item">
                <h2>12. Pembubaran Kesatuan</h2>
                <p>Kesatuan ini tidak boleh dibubarkan dengan sendiri melainkan dengan undi rahsia sekurang-kurangnya setengah (1/2) anggota-anggota yang layak untuk mengundi dikembalikan dan sekurang-kurangnya 50% dari undi yang dikembalikan bersetuju untuk pembubaran kesatuan.</p>
                <p>Jika sekiranya kesatuan ini dibubarkan, segala hutang dan tanggungan yang dibuat dengan cara sah bagi pihak kesatuan hendaklah dijelaskan dengan sepenuhnya dan baki wang yang tinggal hendaklah diselesaikan menurut keputusan yang akan dibuat dengan undi rahsia.</p>
            </div>

